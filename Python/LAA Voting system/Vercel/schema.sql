-- Run once against a fresh Neon database before deployment.
CREATE TABLE IF NOT EXISTS members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  licence TEXT NOT NULL UNIQUE,
  name TEXT,
  present INTEGER NOT NULL DEFAULT 1,
  pin TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS members_licence_ci ON members (lower(licence));
CREATE TABLE IF NOT EXISTS ballots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id BIGINT REFERENCES members(id),
  label TEXT,
  club TEXT
);
CREATE TABLE IF NOT EXISTS votes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT,
  secret INTEGER,
  options TEXT,
  status TEXT DEFAULT 'open',
  eligible INTEGER,
  code TEXT,
  live INTEGER DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS one_open_vote ON votes (status) WHERE status = 'open';
CREATE TABLE IF NOT EXISTS vote_cast (
  vote_id BIGINT NOT NULL REFERENCES votes(id),
  ballot_id BIGINT NOT NULL REFERENCES ballots(id),
  PRIMARY KEY(vote_id, ballot_id)
);
CREATE TABLE IF NOT EXISTS tally (
  vote_id BIGINT NOT NULL REFERENCES votes(id),
  choice TEXT NOT NULL,
  n INTEGER NOT NULL,
  PRIMARY KEY(vote_id, choice)
);
CREATE TABLE IF NOT EXISTS open_choices (
  vote_id BIGINT NOT NULL REFERENCES votes(id),
  ballot_id BIGINT NOT NULL REFERENCES ballots(id),
  choice TEXT
);
CREATE TABLE IF NOT EXISTS confirmed (
  vote_id BIGINT NOT NULL REFERENCES votes(id),
  member_id BIGINT NOT NULL REFERENCES members(id),
  PRIMARY KEY(vote_id, member_id)
);
CREATE TABLE IF NOT EXISTS roster (
  licence TEXT PRIMARY KEY,
  name TEXT,
  club TEXT,
  voting INTEGER DEFAULT 1
);
CREATE UNIQUE INDEX IF NOT EXISTS roster_licence_ci ON roster (lower(licence));

-- Execute this file once for an EXISTING PostgreSQL voting database.
CREATE TABLE IF NOT EXISTS admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS admin_username_ci ON admin_users (lower(username));

CREATE TABLE IF NOT EXISTS admin_sessions (
    token_hash CHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES admin_users(id) ON DELETE CASCADE,
    csrf_token TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS admin_sessions_expiration ON admin_sessions (expires_at);

CREATE TABLE IF NOT EXISTS admin_login_attempts (
    key TEXT NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS admin_login_attempts_recent ON admin_login_attempts (key, occurred_at);
